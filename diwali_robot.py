class DiwaliSim:
    CTRL_EVERY = 4          # physics steps per control update (8 ms)
    N_PT = 2400

    def __init__(self, text='HAPPY DIWALI', speed=1.0, kannada=True, seed=7):
        self.rng = np.random.default_rng(seed)
        self.speed = float(speed)
        self.paused = False
        kn, kh = (layout_kannada((0.745, 0.625)) if kannada else ([], 0.0))
        en_zc = 0.465 if kannada else 0.62
        en = layout_english(text, zc=en_zc, smax=0.016, wmax=0.50, hmax=0.07)
