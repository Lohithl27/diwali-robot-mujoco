def apply_cam(cam, sim):
    look, dist, az, el = sim.cam_params(sim.tau)
    cam.type = mujoco.mjtCamera.mjCAMERA_FREE
    cam.lookat[:] = look
    cam.distance, cam.azimuth, cam.elevation = dist, az, el
    return (look, dist, az, el)


def save_png(path, rgb):
    h, w, _ = rgb.shape
    raw = b''.join(b'\x00' + rgb[y].tobytes() for y in range(h))

    def chunk(tag, data):
        c = struct.pack('>I', len(data)) + tag + data
        return c + struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff)
    png = (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0))
           + chunk(b'IDAT', zlib.compress(raw, 6)) + chunk(b'IEND', b''))
    with open(path, 'wb') as f:
        f.write(png)


class FrameWriter:
    def __init__(self, path, fps, w, h):
        self.kind, self.n, self.path = None, 0, path
        if path.lower().endswith('.mp4'):
            try:
                import imageio.v2 as iio
                self.w = iio.get_writer(path, fps=fps, codec='libx264', macro_block_size=1, quality=7)
                self.kind = 'imageio'
            except Exception:
                if shutil.which('ffmpeg'):
                    self.w = subprocess.Popen(
                        ['ffmpeg', '-y', '-loglevel', 'error', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-s', '%dx%d' % (w, h),
                         '-r', str(fps), '-i', '-', '-an', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', path], stdin=subprocess.PIPE)
                    self.kind = 'ffmpeg'
        if self.kind is None:
            self.path = os.path.splitext(path)[0] + '_frames'
            os.makedirs(self.path, exist_ok=True)
            self.kind = 'png'
            print('[info] no video encoder found -> writing PNG frames to %s/' % self.path)

    def write(self, rgb):
        if self.kind == 'imageio':
            self.w.append_data(rgb)
        elif self.kind == 'ffmpeg':
            self.w.stdin.write(rgb.tobytes())
        else:
            save_png(os.path.join(self.path, 'f%05d.png' % self.n), rgb)
        self.n += 1

    def close(self):
        if self.kind == 'imageio':
            self.w.close()
        elif self.kind == 'ffmpeg':
            self.w.stdin.close()
            self.w.wait()


HELP = 'UP/DOWN or +/- = speed   0 = normal   SPACE = pause   R = replay   C = auto/free camera'


def run_viewer(sim):
    import mujoco.viewer
    state = {'auto': True, 'last': None}

    def show(v):
        try:
            v.set_texts((mujoco.mjtFontScale.mjFONTSCALE_150, mujoco.mjtGridPos.mjGRID_TOPLEFT,
                         'Speed %.2fx%s' % (sim.speed, '   (PAUSED)' if sim.paused else ''), HELP))
        except Exception:
            pass

    def key_cb(keycode):
        if keycode in (265, 61, 334, 43):             # UP, '=', KP+, '+'
            sim.speed = min(sim.speed * 1.25, 3.0)
        elif keycode in (264, 45, 333):               # DOWN, '-', KP-
            sim.speed = max(sim.speed / 1.25, 0.2)
        elif keycode in (48, 320):                    # '0'
            sim.speed = 1.0
        elif keycode == 32:
            sim.paused = not sim.paused
        elif keycode in (82, 114):                    # R
            sim.reset()
            state['auto'] = True
        elif keycode in (67, 99):                     # C
            state['auto'] = not state['auto']
        else:
            return
        print('speed %.2fx%s' % (sim.speed, ' (paused)' if sim.paused else ''))

    try:
        try:
            v = mujoco.viewer.launch_passive(sim.m, sim.d, key_callback=key_cb, show_left_ui=False, show_right_ui=False)
        except TypeError:
            v = mujoco.viewer.launch_passive(sim.m, sim.d, key_callback=key_cb)
    except RuntimeError as e:
        print('\n[!] Could not open the viewer:', e)
        print('    On macOS the live viewer must be started with:  mjpython diwali_robot.py')
        print('    (or record a video with:  python3 diwali_robot.py --record diwali.mp4)')
        return
    print(HELP)
    wall0, sim_t0 = time.time(), 0.0
    last_speed, last_pause = None, None
    with v:
        apply_cam(v.cam, sim)
        while v.is_running():
            tic = time.time()
            with v.lock():
                sim.advance()
                if state['auto']:
                    # if the user dragged the mouse, hand the camera over to them
                    cur = (float(v.cam.azimuth), float(v.cam.distance), float(v.cam.elevation))
                    if state['last'] is not None and max(abs(a - b) for a, b in zip(cur, state['last'])) > 1e-3:
                        state['auto'] = False
                    else:
                        _, dist, az, el = apply_cam(v.cam, sim)[0], *apply_cam(v.cam, sim)[1:]
                        state['last'] = (float(v.cam.azimuth), float(v.cam.distance), float(v.cam.elevation))
            if (sim.speed, sim.paused) != (last_speed, last_pause):
                show(v)
                last_speed, last_pause = sim.speed, sim.paused
            v.sync()
            sleep = sim.spf * sim.m.opt.timestep - (time.time() - tic)       # real-time pacing
            if sleep > 0:
                time.sleep(sleep)


def render_run(sim, fps, width, height, out=None, stills=None):
    dt = sim.m.opt.timestep
    sim.spf = max(1, round(1.0 / (fps * dt)))
    ren = mujoco.Renderer(sim.m, height=height, width=width)
    cam = mujoco.MjvCamera()
    wr = FrameWriter(out, fps, width, height) if out else None
    stills = sorted(stills or [], key=lambda s: s[0])
    t0, last = time.time(), -10
    while sim.tau < sim.t_end:
        sim.advance()
        apply_cam(cam, sim)
        if stills and sim.tau >= stills[0][0]:
            ren.update_scene(sim.d, camera=cam)
            save_png(stills[0][1], ren.render())
            print('saved', stills[0][1])
            stills.pop(0)
        if wr is not None:
            ren.update_scene(sim.d, camera=cam)
            wr.write(ren.render())
            pct = int(100 * sim.tau / sim.t_end)
            if pct >= last + 10:
                print('  rendering... %d%%' % pct)
                last = pct
    if wr is not None:
        wr.close()
        print('saved %s  (%d frames, %.0fs)' % (wr.path, wr.n, time.time() - t0))


def run_selftest(sim):
    t0 = time.time()
    w_errs, errs, nan = [], [], False
    while sim.tau < sim.t_end:
        sim.advance()
        e = sim.tip_error()
        errs.append(e)
        if sim.ink_active:
            w_errs.append(e)
        if not np.all(np.isfinite(sim.d.qpos)):
            nan = True
            break
    e, w = np.array(errs), np.array(w_errs)
    print('show length %.1fs (script time) simulated in %.1fs | ink dots %d/%d' % (sim.tau, time.time() - t0, sim.n_dots, sim.n_ink))
    print('pen error while writing: rms %.1f mm, max %.1f mm | overall max %.1f mm' %
          (1000 * np.sqrt(np.mean(w ** 2)), 1000 * w.max(), 1000 * e.max()))
    print('rocket launched: %s, blasted: %s' % (sim.launched, sim.blasted))
    ok = (not nan) and np.sqrt(np.mean(w ** 2)) < 0.006 and sim.launched and sim.blasted and sim.n_dots > 500
    print('SELFTEST', 'PASSED' if ok else 'FAILED')
    return 0 if ok else 1


