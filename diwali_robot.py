# --------------------------------------------------------------------------- #
#  Damped least-squares inverse kinematics (position + pen direction)
# --------------------------------------------------------------------------- #
class ArmIK:
    def __init__(self, m, site, q_guess):
        self.m, self.site = m, site
        self.d = mujoco.MjData(m)
        self.q = np.array(q_guess, float)
        self.q_home = self.q.copy()
        self.lo, self.hi = m.jnt_range[:6, 0] + 0.02, m.jnt_range[:6, 1] - 0.02
        self.jp, self.jr = np.zeros((3, m.nv)), np.zeros((3, m.nv))

    def solve(self, pos, axis=AXIS, iters=4, w=0.3, lam=1e-4, k_null=0.1):
        m, d = self.m, self.d
        for _ in range(iters):
            d.qpos[:6] = self.q
            mujoco.mj_kinematics(m, d)
            mujoco.mj_comPos(m, d)
            mujoco.mj_jacSite(m, d, self.jp, self.jr, self.site)
            a = d.site_xmat[self.site].reshape(3, 3)[:, 2]
            e = np.concatenate([pos - d.site_xpos[self.site], w * np.cross(a, axis)])
            J = np.vstack([self.jp, w * self.jr])
            Jp = J.T @ np.linalg.inv(J @ J.T + lam * np.eye(6))
            dq = Jp @ e + (np.eye(6) - Jp @ J) @ (k_null * (self.q_home - self.q))
            self.q = np.clip(self.q + np.clip(dq, -0.15, 0.15), self.lo, self.hi)
        return self.q


