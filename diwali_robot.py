def _advance(ch):
    if ch == ' ':
        return 1.4
    return max(p[0] for s in FONT[ch] for p in s) + 0.8


def layout_english(text, zc, smax=0.030, wmax=0.60, hmax=0.34):
    lines = [''.join(c if c in FONT else ' ' for c in ln.upper()).strip() for ln in text.split('|')]
    widths = [max(sum(_advance(c) for c in ln) - 0.8, 1.0) for ln in lines]
    nl = len(lines)
    block_h = 4 * nl + 2 * (nl - 1)
    s = min(smax, wmax / max(widths), hmax / block_h)
    strokes, gi = [], 0
    for li, ln in enumerate(lines):
        u0 = -widths[li] * s / 2.0
        base = zc + block_h * s / 2.0 - 4 * s - li * 6 * s
        cur = 0.0
        for ch in ln:
            if ch != ' ':
                for st in FONT[ch]:
                    pts = np.array([[-(u0 + (cur + x) * s), base + yy * s] for x, yy in st])   # y = -u
                    strokes.append((pts, PALETTE[gi % len(PALETTE)]))
                gi += 1
            cur += _advance(ch)
    return strokes


def layout_kannada(zcs, width=0.62):
    """Two lines of the Kannada greeting; returns (strokes, line_height_m)."""
    s = width / max(w for w, _ in KN_LINES)          # metres per em
    H = KN_HEIGHT * s
    strokes = []
    for li, (w, contours) in enumerate(KN_LINES):
        bottom = zcs[li] - H / 2.0
        for i, c in enumerate(contours):
            pts = np.array([[-((x - w / 2.0) * s), bottom + y * s] for x, y in c])
            strokes.append((pts, KN_PALETTE[(i + 2 * li) % len(KN_PALETTE)]))
    return strokes, H


def wavy_line(zc, half):
    uu = np.linspace(-half, half, 70)
    return (np.stack([-uu, zc + 0.008 * np.sin(2 * math.pi * uu / 0.07)], axis=1), PALETTE[0])


