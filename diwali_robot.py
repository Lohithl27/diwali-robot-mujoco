def board_pt(y, z, up):
    return np.array([BOARD_X - 0.003 - PEN_UP * up, y, z])


class Timeline:
    def __init__(self, pos, axis):
        self.t = 0.0
        self.pos, self.axis = np.array(pos, float), np.array(axis, float)
        self.segs, self.starts = [], []

    def add(self, pos, dur, ease=False, ink=False, col=(1, 1, 1), axis=None):
        pos = np.array(pos, float)
        axis = self.axis if axis is None else np.array(axis, float)
        self.segs.append((self.t, self.t + dur, self.pos.copy(), pos, self.axis.copy(), axis, ease, ink, col))
        self.starts.append(self.t)
        self.t += dur
        self.pos, self.axis = pos, axis

    def at(self, t):
        if t >= self.t:
            return self.pos, self.axis, False, (1, 1, 1)
        i = max(bisect.bisect_right(self.starts, t) - 1, 0)
        t0, t1, p0, p1, a0, a1, ease, ink, col = self.segs[i]
        a = min(max((t - t0) / (t1 - t0), 0.0), 1.0)
        if ease:
            a = a * a * (3 - 2 * a)
        ax = a0 + (a1 - a0) * a
        return p0 + (p1 - p0) * a, ax / np.linalg.norm(ax), ink, col


def build_timeline(start_pos, kn_strokes, en_strokes, write_speed, travel_speed=0.9):
    tl = Timeline(start_pos, AXIS)
    marks = {}
    tl.add(start_pos, 0.6)

    def write(strokes, speed):
        for pts, col in strokes:
            a = pts[0]
            if tl.pos[0] > BOARD_X - 0.02:       # pen is down -> lift first
                tl.add(board_pt(tl.pos[1], tl.pos[2], 1.0), 0.09, True)
            tgt_up = board_pt(a[0], a[1], 1.0)
            d = float(np.linalg.norm(tgt_up - tl.pos))
            tl.add(tgt_up, max(0.16, d / travel_speed), True)
            tl.add(board_pt(a[0], a[1], 0.0), 0.09, True)
            for p in pts[1:]:
                tgt = board_pt(p[0], p[1], 0.0)
                L = float(np.linalg.norm(tgt - tl.pos))
                tl.add(tgt, max(L / speed, 1e-3), False, True, col)
        tl.add(board_pt(tl.pos[1], tl.pos[2], 1.0), 0.15, True)

    if kn_strokes:
        write(kn_strokes, write_speed * 1.2)
    marks['kn_done'] = tl.t
    write(en_strokes, write_speed)
    marks['en_done'] = tl.t

    # a little "namaste" wave
    tl.add(board_pt(0.0, 0.62, 1.0), 0.8, True, axis=AXIS)
    for k in range(4):
        tl.add(board_pt(0.14 * (-1) ** k, 0.62, 1.0), 0.35, True)
    # go and light the rocket fuse
    radial = np.array([math.cos(ROCKET_ANG), math.sin(ROCKET_ANG), -0.30])
    radial /= np.linalg.norm(radial)
    fuse = np.array([RX, RY, ROCKET_Z0 + FUSE_BOTTOM])           # the wick at the BOTTOM of the rocket
    touch = fuse - 0.015 * radial
    approach = touch - 0.14 * radial + np.array([0, 0, 0.06])
    tl.add(approach, 1.6, True, axis=radial)
    marks['approach'] = tl.t
    tl.add(touch, 0.6, True)
    marks['touch'] = tl.t
    tl.add(touch + np.array([0, 0.004, 0.0]), 1.0)                 # hold: fuse is sparking
    tl.add(approach + 0.05 * (-radial), 0.8, True)
    marks['retreat'] = tl.t
    tl.add(board_pt(0.0, 0.66, 1.0), 1.2, True, axis=AXIS)
    marks['launch'] = marks['touch'] + 1.0 + 1.5                       # fuse burns ~1.7 s after the hold
    marks['blast'] = marks['launch'] + FLIGHT_T
    # keep the cobot cheering until the show is over
    k = 0
    while tl.t < marks['blast'] + 6.0:
        tl.add(board_pt(0.16 * (-1) ** k, 0.70, 1.0), 0.5, True)
        k += 1
    marks['end'] = marks['blast'] + 6.5
    return tl, marks


